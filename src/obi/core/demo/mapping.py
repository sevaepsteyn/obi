"""The private real→fictional mapping (feature 134, data-model §PseudonymMap, FR-004/FR-014).

One :class:`PseudonymMap` holds every identity assignment of a dataset — places (word-level),
people, mesh nodes, SSIDs, domains, MACs, serials, and the IP remap — under a 32-byte seed.
Assignments are append-only: a later snapshot loads the file first and only ever adds entities,
so fictional names stay stable across runs (US5-2). The file is written owner-only (0600) and
must never sit inside a dataset directory (enforced by the profile).
"""

from __future__ import annotations

import hashlib
import hmac
import json
import os
import re
import stat
from pathlib import Path
from typing import Any

from obi.core.demo import ProfileError
from obi.core.demo.ipremap import IpRemapper
from obi.core.demo.naming import (
    TREES,
    domain_label,
    node_label,
    person_label,
    place_label,
    ssid_label,
    within_one_edit,
)

MAPPING_VERSION = 1
CLASSES = ("place", "person", "node", "ssid", "domain", "mac", "serial", "callsign")
#: Classes whose fakes are hand-curated (feature 137): never generated by :meth:`_assign`.
CURATED = frozenset({"callsign"})

_HEX12 = re.compile(r"[^0-9a-f]")


def normalize_mac(text: str) -> str | None:
    """12 lower-hex digits for any MAC spelling (``:``/``-``/``.``/bare, any case), else None."""

    digits = _HEX12.sub("", text.casefold())
    return digits if len(digits) == 12 else None


class PseudonymMap:
    """Deterministic, append-only, per-class identity mapping (research R4)."""

    def __init__(self, seed: bytes, data: dict[str, Any] | None = None) -> None:
        data = data or {}
        self.seed = seed
        self._classes: dict[str, dict[str, str]] = {
            cls: dict(data.get("classes", {}).get(cls, {})) for cls in CLASSES
        }
        self.ip = IpRemapper(seed, data.get("ip"))
        self.geo: dict[str, Any] = dict(data.get("geo", {}))
        self.time: dict[str, Any] = dict(data.get("time", {}))
        # Feature 137 — kept OUTSIDE ``geo``, which 134's prepare() rewrites on every snapshot.
        fixtures = data.get("fixtures", {})
        dlon = fixtures.get("dlon")
        self.fixture_dlon: float | None = float(dlon) if dlon is not None else None
        self.pairs: list[list[str]] = [list(p) for p in fixtures.get("pairs", [])]
        self._forbidden: frozenset[str] = frozenset()
        self._fakes: dict[str, set[str]] = {
            cls: set(values.values()) for cls, values in self._classes.items()
        }

    # -- persistence --------------------------------------------------------------------------

    @classmethod
    def load_or_create(cls, path: Path) -> PseudonymMap:
        if not path.exists():
            return cls(os.urandom(32))
        mode = stat.S_IMODE(path.stat().st_mode)
        if mode & 0o077:
            raise ProfileError(f"private mapping {path} must be owner-only (chmod 600)")
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
            seed = bytes.fromhex(data["seed"])
        except (OSError, ValueError, KeyError) as exc:
            raise ProfileError(f"private mapping {path} is unreadable: {exc}") from exc
        if data.get("version") != MAPPING_VERSION:
            raise ProfileError(f"private mapping {path} has an unsupported version")
        return cls(seed, data)

    def to_dict(self) -> dict[str, Any]:
        return {
            "version": MAPPING_VERSION,
            "seed": self.seed.hex(),
            "classes": {cls: dict(sorted(self._classes[cls].items())) for cls in CLASSES},
            "ip": self.ip.state(),
            "geo": self.geo,
            "time": self.time,
            "fixtures": {"dlon": self.fixture_dlon, "pairs": self.pairs},
        }

    def save(self, path: Path) -> None:
        """Atomically write the mapping owner-only (0600) — the parent dir is made 0700."""

        path.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
        tmp = path.with_name(path.name + ".tmp")
        fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            json.dump(self.to_dict(), handle, indent=1, sort_keys=False)
            handle.write("\n")
        os.chmod(tmp, 0o600)
        os.replace(tmp, path)

    # -- assignment ---------------------------------------------------------------------------

    def forbid(self, real_tokens: set[str]) -> None:
        """Real casefolded tokens no fictional value may equal (or, for places, nearly equal)."""

        self._forbidden = frozenset(t.casefold() for t in real_tokens)

    def _digest(self, *parts: str) -> int:
        mac = hmac.new(self.seed, "\x1f".join(parts).encode(), hashlib.sha256)
        return int.from_bytes(mac.digest()[:8], "big")

    def _hexdigest(self, *parts: str) -> str:
        return hmac.new(self.seed, "\x1f".join(parts).encode(), hashlib.sha256).hexdigest()

    def _place_ok(self, label: str) -> bool:
        if label in self._forbidden:
            return False
        # Never within one edit of a real token (the gate's fuzzy check), and never CONTAINING a
        # long real token (the gate matches tokens of 6+ characters as substrings).
        return not any(
            (len(real) >= 4 and within_one_edit(label, real)) or (len(real) >= 6 and real in label)
            for real in self._forbidden
        )

    def _assign(self, cls: str, real: str) -> str:
        table = self._classes[cls]
        found = table.get(real)
        if found is not None:
            return found
        taken = self._fakes[cls]
        if cls == "place":
            start = self._digest("place", real) % len(TREES)
            index = start
            while True:
                label = place_label(index)
                if label not in taken and self._place_ok(label):
                    break
                index += 1
        elif cls in ("person", "node", "ssid", "domain"):
            make = {
                "person": person_label,
                "node": node_label,
                "ssid": ssid_label,
                "domain": domain_label,
            }[cls]
            index = len(taken)
            while (label := make(index)) in taken or label.casefold() in self._forbidden:
                index += 1
        elif cls == "mac":
            counter = 0
            while True:
                digest = self._hexdigest("mac", real, str(counter))
                label = "02" + digest[:10]
                if label not in taken and label != real:
                    break
                counter += 1
        elif cls == "serial":
            counter = 0
            while True:
                label = self._hexdigest("serial", real, str(counter))[:12].upper()
                if label not in taken and label.casefold() not in self._forbidden:
                    break
                counter += 1
        else:  # curated classes are never generated
            raise KeyError(f"{cls} fakes are curated: no assignment for this value")
        table[real] = label
        taken.add(label)
        return label

    def opaque(self, cls: str, real: str, *, width: int = 6) -> str:
        """A stable, unstored pseudonym (``client-3fa9c1``) for values too numerous to tabulate,
        such as the hostnames visitors' phones announce over DHCP. HMAC-derived from the seed, so
        it is identical across runs and reveals nothing."""

        return f"{cls}-{self._hexdigest(cls, real.casefold())[:width]}"

    def place(self, word: str) -> str:
        return self._assign("place", word.casefold())

    def peek_place(self, word: str) -> str | None:
        """The assigned tree word for ``word`` without assigning a new one."""

        return self._classes["place"].get(word.casefold())

    def person(self, real: str) -> str:
        return self._assign("person", real.casefold())

    def node(self, real: str) -> str:
        return self._assign("node", real.casefold())

    def ssid(self, real: str) -> str:
        return self._assign("ssid", real)

    def domain(self, real: str) -> str:
        return self._assign("domain", real.casefold())

    def serial(self, real: str) -> str:
        return self._assign("serial", real.upper())

    def mac(self, real: str) -> str:
        """The fake MAC as 12 lower-hex digits (callers re-apply the original spelling)."""

        normalized = normalize_mac(real)
        if normalized is None:
            raise ValueError("not a MAC address")
        return self._assign("mac", normalized)

    def callsign(self, real: str) -> str:
        """The curated fictional callsign for ``real`` (KeyError when none is curated yet)."""

        return self._classes["callsign"][real.casefold()]

    def set_callsign(self, real: str, fake: str) -> None:
        """Curate a fictional single-token callsign (feature 137, research D6)."""

        label = fake.strip()
        if not label or any(ch.isspace() for ch in label):
            raise ValueError("a callsign fake must be a single token")
        key = real.strip().casefold()
        table = self._classes["callsign"]
        owner = next((r for r, f in table.items() if f.casefold() == label.casefold()), None)
        if owner is not None and owner != key:
            raise ValueError("that fake is already curated for another callsign")
        table[key] = label
        self._fakes["callsign"].add(label)

    def has_mac(self, normalized: str) -> bool:
        return normalized in self._classes["mac"]

    def assignments(self, cls: str) -> dict[str, str]:
        return dict(self._classes[cls])

    def reverse(self, fake: str) -> list[tuple[str, str]]:
        """Every (class, real) whose fictional value is ``fake`` (local operator lookup only)."""

        wanted = fake.casefold()
        hits: list[tuple[str, str]] = []
        for cls in CLASSES:
            for real, value in self._classes[cls].items():
                if value.casefold() == wanted:
                    hits.append((cls, real))
        return hits

    def lookup(self, real: str) -> list[tuple[str, str]]:
        """Every (class, fake) assigned to ``real``, plus its IP mapping when it is an address."""

        wanted = real.casefold()
        hits: list[tuple[str, str]] = []
        for cls in CLASSES:
            for key, value in self._classes[cls].items():
                if key.casefold() == wanted:
                    hits.append((cls, value))
        mapped = self.ip.map_ip(real)
        if mapped != real:
            hits.append(("ip", mapped))
        return hits
