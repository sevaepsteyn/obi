"""The dataset's fictional ``config.toml`` (feature 134, T039).

Generated from the real config's STRUCTURE so feature 135 (``obi web --demo``) runs with the same
feature set: identifiers mapped, every secret replaced by ``"demo"``, the weather point relocated,
host paths dropped (the XDG defaults then resolve inside the dataset) and the OSPF layout pointed
at the dataset's copy. Sections that only make sense on the live host or carry people — the radio,
paging, Slack, WLED, launchd service, NetBox, VictoriaMetrics, gate-traffic, UniFi-internal and
the ``[demo]`` profile itself — are dropped. The output must round-trip through ``load_config``.
"""

from __future__ import annotations

import json
import re
from typing import Any

from obi.core.demo import SourceError
from obi.core.demo.sources import INCLUDED, SourceContext, SourceReport

NAME = "config"
DEMO_SECRET = "demo"
DROPPED_SECTIONS = frozenset(
    {
        "demo", "radio", "paging", "slack", "wled", "service", "netbox", "victoria", "traffic",
        "unifi-internal", "voice",
    }
)  # fmt: skip
_SECRET_KEY = re.compile(
    r"(pass(word|wd|phrase)?|secret|token|api[_-]?key|community|v3_(auth|priv)_key|psk)$",
    re.IGNORECASE,
)
_PATH_KEY = re.compile(r"(_path|_dir|_root|_file)$|^(db_path|mirror_root|export_path)$")
_PEOPLE_KEY = re.compile(
    r"(slack|allowlist|recipients|callers|aliases|handles|pronunciations|names|report_only"
    r"|vocab|username|user)$",
    re.IGNORECASE,
)
_BARE_KEY = re.compile(r"^[A-Za-z0-9_-]+$")
OSPF_LAYOUT_REL = "state/obi/ospf-layout.json"


def _sanitize(ctx: SourceContext, table: dict[str, Any], path: tuple[str, ...]) -> dict[str, Any]:
    rw = ctx.rewriter
    out: dict[str, Any] = {}
    for key, value in table.items():
        here = (*path, key)
        if not path and key in DROPPED_SECTIONS:
            continue
        if key == "username" and isinstance(value, str):
            out[key] = DEMO_SECRET  # required beside a password by the loader
            continue
        if _PEOPLE_KEY.search(key):
            continue  # people, handles, node names — tables included
        if isinstance(value, str) and _SECRET_KEY.search(key):
            out[key] = DEMO_SECRET
            continue
        if key == "ospf_layout_path":
            out[key] = OSPF_LAYOUT_REL
            continue
        if isinstance(value, str) and _PATH_KEY.search(key):
            continue
        new_key = rw.ident(key) if path and path[-1] in ("site_towers", "ground_overrides") else key
        if isinstance(value, dict):
            out[new_key] = _sanitize(ctx, value, here)
        elif isinstance(value, list):
            out[new_key] = [
                _sanitize(ctx, v, here) if isinstance(v, dict)
                else rw.ident(v) if isinstance(v, str) else v
                for v in value
            ]  # fmt: skip
        elif isinstance(value, str):
            out[new_key] = rw.ident(value) if key in ("device", "label", "name") else rw.text(value)
        else:
            out[new_key] = value
    return out


def build_config(ctx: SourceContext) -> dict[str, Any]:
    config = _sanitize(ctx, dict(ctx.raw_config), ())
    weather = config.get("weather")
    if isinstance(weather, dict) and "latitude" in weather and "longitude" in weather:
        lat, lon = ctx.relocator.point(float(weather["latitude"]), float(weather["longitude"]))
        weather["latitude"], weather["longitude"] = round(lat, 5), round(lon, 5)
    web = config.setdefault("web", {})
    if isinstance(web, dict):
        web["gnis_states"] = [ctx.profile.gnis_state]
        web.pop("brc", None)  # the city-grid toggle names the event; the grid is never shipped
        if (ctx.out_state / "ospf-layout.json").exists():
            web["ospf_layout_path"] = OSPF_LAYOUT_REL
    if isinstance(config.get("uisp"), dict):
        config["uisp"].pop("name_filter", None)
        config["uisp"].pop("ignore_names", None)
    # Outbound surfaces have nothing behind them in a demo (their sections are dropped above):
    # switch their senders off, or the config would not load ([watch] slack_notify without a
    # [slack] bot_token is a load error — found by feature 136's first export).
    watch = config.get("watch")
    if isinstance(watch, dict):
        watch["slack_notify"] = False
    dash = config.get("dash")
    if isinstance(dash, dict):
        for sub in ("pager", "status_band"):
            if isinstance(dash.get(sub), dict):
                dash[sub]["enabled"] = False
    return config


def run(ctx: SourceContext) -> SourceReport:
    config = build_config(ctx)
    header = (
        "# Example Valley Net — fictional demo configuration generated by `obi demo snapshot`.\n"
        '# Every credential is the placeholder "demo"; every address and name is fictional.\n\n'
    )
    path = ctx.out_state.parent.parent / "config.toml"
    path.write_text(header + dumps_toml(config), encoding="utf-8")
    # The dataset's config must be loadable by obi itself (feature 136 renders through it).
    from obi.core.config import ConfigError, load_config

    try:
        load_config(path)
    except ConfigError as exc:
        raise SourceError(f"the generated demo config does not load: {exc}") from exc
    return SourceReport(NAME, INCLUDED, rows_in=len(ctx.raw_config), rows_out=len(config))


# --- a minimal TOML writer (obi has no TOML-writing dependency) -------------------------------


def _key(key: str) -> str:
    return key if _BARE_KEY.match(key) else json.dumps(key, ensure_ascii=False)


def _value(value: Any) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int | float):
        return repr(value)
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    if isinstance(value, list):
        return "[" + ", ".join(_value(v) for v in value) + "]"
    raise TypeError(f"unsupported TOML value: {type(value).__name__}")


def dumps_toml(data: dict[str, Any], prefix: tuple[str, ...] = ()) -> str:
    """Serialize nested dicts/lists/scalars (no datetimes) as TOML, scalars before tables."""

    lines: list[str] = []
    tables: list[tuple[str, dict[str, Any]]] = []
    arrays: list[tuple[str, list[dict[str, Any]]]] = []
    for key, value in data.items():
        if isinstance(value, dict):
            tables.append((key, value))
        elif isinstance(value, list) and value and all(isinstance(v, dict) for v in value):
            arrays.append((key, value))
        else:
            lines.append(f"{_key(key)} = {_value(value)}")
    out = "\n".join(lines) + ("\n" if lines else "")
    for key, table in tables:
        name = ".".join(_key(k) for k in (*prefix, key))
        body = dumps_toml(table, (*prefix, key))
        out += f"\n[{name}]\n{body}"
    for key, items in arrays:
        name = ".".join(_key(k) for k in (*prefix, key))
        for item in items:
            out += f"\n[[{name}]]\n" + dumps_toml(item, (*prefix, key))
    return out
